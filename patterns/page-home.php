      <h2 class="wp-block-heading arcn-home-welcome__title">Welcome to the <strong>Austrian Restored Citizenship Network</strong> (ARCN).</h2>
      <!-- /wp:heading -->

      <!-- wp:paragraph -->
      <p>We are a small, but ever-growing group of ‘new’ Austrian citizens. We are committed to developing a vibrant and active Network by sharing information, ideas and projects inspired by our recently restored Austrian citizenship.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>We recognise the reasons for our restored citizenship are by no means straightforward. Thus, we seek to foster open and honest dialogue – both between ourselves, as well as our fellow Austrian citizens – where appropriate.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>Whilst those applying for citizenship may have a multitude of reasons, in an increasingly turbulent world, citizenship is subject to continuous processes of scrutiny, negotiation and politicisation.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>Irrevocably linked by our shared and tragic past, and literally scattered across all continents of the world – the ARCN seeks to establish an infrastructure for information-sharing and education, community-building and dialogue, and even civic participation.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>In developing and launching this website – the Austrian Restored Citizenship Network (ARCN) – seeks to address the many questions, reflections and ideas arising from the restoration of Austrian citizenship.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>In addition to addressing practical issues, and hopefully answering some of the many questions arising for those seeking citizenship, we hope to develop a dialogue between ourselves.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>We intend to create a forum offering the opportunity to reflect on what else we might be interested in – both now, and in the future. At the same time – we believe a digital home is not always enough, so we will also use this platform to discuss ways in which we can meet ‘in person’. For example, by regular on-line meetings to discuss topics of interest and an in-person conference in Vienna which we hope to hold in May 2027 (more details to follow).</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>Since 2020, over 45,000 people have successfully applied for Austrian citizenship under the so-called Article 58c Amendment.<br>We are also known in Austria as ‘<em>Wiederoesterreicher: innen</em>’ – literally ‘again Austrians’ or simply 58c citizens.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>As a new chapter opens, perhaps for some, a sense of purpose, creativity, opportunity and responsibility emerges.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>We do not have a formal membership as such, but if you would like to receive information, or make suggestions regarding topics to include on the website, please contact us and register your interest.</p>
      <!-- /wp:paragraph -->

      <!-- wp:paragraph -->
      <p>We are grateful for funding support from the Austrian Federal Ministry for European and International Affairs, the Nationalfonds and the Zukunfstfonds, and to the Vienna Institute for Contemporary and Cultural History and Arts (VICCA) and the University of Applied Arts Vienna for their ongoing support and encouragement.</p>
